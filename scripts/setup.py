#!/usr/bin/env python3
"""Bootstrap editor's PINNED MIT Three.js dependencies and REAL F01 A-E GLBs.

- Offline-ready after FIRST setup; GitHub Actions checks in all generated assets.
- No tokens, no remote writes, no private GitHub API, no gameplay writes.
- Third-party modules fetched ONLY from exact three@0.180.0.
- Refuses unexpected imports, path traversal and oversized JavaScript.
"""
from __future__ import annotations
import hashlib
import json
import os
import pathlib
import posixpath
import re
import shutil
import subprocess
import sys
import urllib.error
import urllib.request

ROOT=pathlib.Path(__file__).resolve().parents[1]
VERSION="0.180.0"
CDN=(
 "https://cdn.jsdelivr.net/npm/three@"+VERSION+"/",
 "https://unpkg.com/three@"+VERSION+"/",
)
APP_ENTRY=(
 "build/three.module.js",
 "build/three.core.js",
 "examples/jsm/loaders/GLTFLoader.js",
 "examples/jsm/controls/OrbitControls.js",
 "examples/jsm/controls/TransformControls.js",
)
EXPECTED_TEXTURE_SHA="81c434a57b770148ced6e9c40dccabade929a844a27b143f2dc13a4da0ff8c98"
EXPECTED_FULL_SHA="787965608e2e4005a0ee84c857d7f0379a8093149b39da6bacb2d012feafc147"
GLB_NAMES=[
 "f01-marble-cream-full.glb",
 "f01-marble-cream-half-first.glb",
 "f01-marble-cream-half-second.glb",
 *("f01-marble-cream-quarter-c%d.glb"%i for i in range(1,5)),
 *("f01-marble-cream-edge-%s.glb"%s for s in ("north","south","east","west")),
 *("f01-marble-cream-corner-%s.glb"%s for s in ("north-west","north-east","south-east","south-west"))
]
RELATIVE_IMPORT=re.compile(r'''(?:\bfrom\s*|\bimport\s*\(\s*)["'](\.{1,2}/[^"']+)["']''')
USER_AGENT="TrialumWorldBuilder/0.1 (static dependency pin, GitHub Actions)"


def fetch(remote:str,limit=2_500_000)->bytes:
    if remote.startswith("/") or ".." in remote.split("/"):
        raise ValueError("Unexpected upstream path "+remote)
    for base in CDN:
        try:
            request=urllib.request.Request(base+remote,headers={"User-Agent":USER_AGENT})
            with urllib.request.urlopen(request,timeout=18) as r:
                data=r.read(limit+1)
            if len(data)>limit:raise ValueError("Upstream JavaScript too big: "+remote)
            if not data:raise ValueError("Empty upstream "+remote)
            return data
        except (OSError,urllib.error.URLError) as exc:
            error=exc
    raise RuntimeError("Cannot download pinned Three.js "+remote+": "+str(error))


def destination(remote:str)->pathlib.Path:
    if remote.startswith("build/"):
        return ROOT/"vendor"/remote.removeprefix("build/")
    if remote.startswith("examples/jsm/"):
        return ROOT/"vendor/addons"/remote.removeprefix("examples/jsm/")
    if remote=="LICENSE":
        return ROOT/"vendor/THREE-LICENSE.txt"
    raise ValueError("Untrusted vendor file "+remote)


def vendor_three():
    done=set()
    queue=[*APP_ENTRY,"LICENSE"]
    while queue:
        remote=posixpath.normpath(queue.pop(0))
        if remote in done:continue
        if not (remote=="LICENSE" or remote in APP_ENTRY or
                remote.startswith("examples/jsm/") or remote.startswith("build/")):
            raise ValueError("Unrecognized import path "+remote)
        path=destination(remote)
        data=path.read_bytes() if path.exists() else fetch(remote)
        path.parent.mkdir(parents=True,exist_ok=True)
        if not path.exists():path.write_bytes(data)
        done.add(remote)
        if remote.endswith(".js"):
            source=data.decode("utf-8")
            for module in RELATIVE_IMPORT.findall(source):
                if not module.endswith(".js"):continue
                next_module=posixpath.normpath(posixpath.join(posixpath.dirname(remote),module))
                if next_module not in done:queue.append(next_module)
    (ROOT/"vendor/VERSION.txt").write_text(
      "three@"+VERSION+" bundled under its MIT license; generated by scripts/setup.py\n",encoding="utf-8")
    print("[vendor] checked",len(done),"pinned Three.js files (JS/addons/LICENSE).")


def build_original_glbs():
    for script in (
       "build-s7-f01-marble.py",
       "build-s7-f01-half.py",
       "build-s7-f01-quarter.py",
       "build-s7-f01-edge.py",
       "build-s7-f01-corner.py",
    ):
        path=ROOT/"tools/b1"/script
        if not path.exists():raise RuntimeError("Missing original authoring script "+str(path))
        subprocess.run([sys.executable,str(path)],check=True,
           stdout=subprocess.DEVNULL,stderr=None,cwd=ROOT)
    dest=ROOT/"assets/models"
    dest.mkdir(parents=True,exist_ok=True)
    all_files={
       x.name:x
       for folder in ("F01-A","F01-B","F01-C","F01-D","F01-E")
       for x in (ROOT/"build/s7-floor-f01"/folder).glob("*.glb")
    }
    assert len(GLB_NAMES)==15 and set(all_files)==set(GLB_NAMES), (
       "Unexpected asset mismatch "+str(set(GLB_NAMES)^set(all_files))
    )
    for name in GLB_NAMES:
        src=all_files[name]
        data=src.read_bytes()
        if data[:4]!=b"glTF" or int.from_bytes(data[8:12],"little")!=len(data):
            raise RuntimeError("Invalid genuine GLB "+name)
        target=dest/name
        if not target.exists() or target.read_bytes()!=data:
            shutil.copy2(src,target)
    a=hashlib.sha256((dest/"f01-marble-cream-full.glb").read_bytes()).hexdigest()
    img=hashlib.sha256((ROOT/"build/s7-floor-f01/F01-A/f01-marble-cream-basecolor.png").read_bytes()).hexdigest()
    if (a,img)!=(EXPECTED_FULL_SHA,EXPECTED_TEXTURE_SHA):
        raise RuntimeError("F01-A owner-approved original GLB or texture has drifted")
    catalog=json.loads((ROOT/"assets/catalog.json").read_text(encoding="utf-8"))
    missing=[x["src"] for x in catalog.get("assets",[])
       if isinstance(x.get("src"),str) and x["src"].endswith(".glb") and x["src"].split("/")[-1] in GLB_NAMES and not (ROOT/x["src"]).is_file()]
    if missing:raise RuntimeError("Missing catalogue files: "+repr(missing))
    print("[assets] checked 15 original real GLBs (A/B/C/D/E), exact A texture/hash PASS.")


def main():
    build_original_glbs()
    vendor_three()
    print("SUCCESS: builder is fully locally runnable with Python or Node server.")


if __name__=="__main__":
    main()
